#!/usr/bin/env python3
"""Generate the Verilog consumed by TT's standard Yosys frontend."""
import argparse
import json
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
sources = json.loads((ROOT / 'test/rtl_import_sha256.json').read_text())
command = [os.environ.get('SV2V', 'sv2v'), '-DSYNTHESIS']
command += ['src/' + Path(name).name for name in sources]
result = subprocess.run(command, cwd=ROOT, check=True, capture_output=True, text=True)
header = '// Generated by scripts/generate_verilog.py using sv2v v0.0.13. Edit the source .sv files.\n'
text = header + result.stdout
output = ROOT / 'src/generated/design.v'
if args.check:
    if not output.exists() or output.read_text() != text:
        raise SystemExit('Generated Verilog is stale; run scripts/generate_verilog.py')
else:
    output.parent.mkdir(exist_ok=True)
    output.write_text(text)
print('Generated Verilog is current.' if args.check else 'Wrote src/generated/design.v')
