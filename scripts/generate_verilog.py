#!/usr/bin/env python3
"""Generate the Verilog consumed by TT's standard Yosys frontend."""
import argparse
import os
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
sources = (ROOT / 'src/sources.f').read_text().splitlines()
command = [os.environ.get('SV2V', 'sv2v'), '-DSYNTHESIS', '-Isrc', '-Isrc/core']
mode = (ROOT / 'src/build_mode.txt').read_text().strip()
if mode not in ('micro', 'direct'):
    raise SystemExit('build_mode.txt must be micro or direct')
if mode == 'direct':
    command.append('-DTT_DIRECT_UCODE')
command += ['src/' + name for name in sources]
result = subprocess.run(command, cwd=ROOT, check=True, capture_output=True, text=True)
header = '// Generated by scripts/generate_verilog.py using sv2v v0.0.13. Edit the sources listed in src/sources.f.\n'
text = header + result.stdout
output = ROOT / 'src/generated/design.v'
if args.check:
    if not output.exists() or output.read_text() != text:
        raise SystemExit('Generated Verilog is stale; run scripts/generate_verilog.py')
else:
    output.parent.mkdir(exist_ok=True)
    output.write_text(text)
print('Generated Verilog is current.' if args.check else 'Wrote src/generated/design.v')
